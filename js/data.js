function getBusinessSettings() {
  const settings = localStorage.getItem('akshar_business_settings');
  if (settings) {
    try {
      const parsed = JSON.parse(settings);
      if (parsed.contactNumber && parsed.address) return parsed;
    } catch (e) {}
  }
  return INITIAL_BUSINESS_SETTINGS;
}

function saveBusinessSettings(newSettings) {
  localStorage.setItem('akshar_business_settings', JSON.stringify(newSettings));
}

